def get_google_calendar_url() -> str:
    """Возвращает URL для добавления события в Google Calendar"""
    from urllib.parse import quote
    
    # Параметры события
    title = "Свадьба Стрельцовых!"
    # Дата: 16 мая 2026, 10:45 по Москве (UTC+3) = 07:45 UTC
    # Формат: YYYYMMDDTHHMMSSZ (UTC)
    start_date = "20260516T074500Z"  # 16 мая 2026, 07:45 UTC (10:45 МСК)
    end_date = "20260516T084500Z"    # 16 мая 2026, 08:45 UTC (11:45 МСК) - длительность 1 час
    
    location = "ЗАГС №4, Бутырская ул., 17, Москва"
    
    yandex_maps_url = "https://yandex.ru/maps/-/CLtHE0NM"
    
    details = (
        "Очень ждём встречи! ✨"
    )
    
    # Формируем URL для Google Calendar
    url = (
        f"https://calendar.google.com/calendar/render?action=TEMPLATE"
        f"&text={quote(title)}"
        f"&dates={start_date}/{end_date}"
        f"&details={quote(details)}"
        f"&location={quote(location)}"
    )
    
    return url


def get_apple_calendar_url() -> str:
    """Возвращает URL для добавления события в Apple Calendar (через .ics файл на Railway)"""
    from config import Config
    
    # URL веб-сервера на Railway, который отдаёт .ics файл
    calendar_server_url = Config.CALENDAR_SERVER_URL
    
    # Если URL не установлен, возвращаем пустую строку (кнопка не будет показана)
    if not calendar_server_url:
        return ""
    
    # На iOS/macOS https:// ссылка на .ics файл откроется напрямую в приложении календаря
    # с предзаполненными данными благодаря правильным заголовкам сервера
    return f"{calendar_server_url}/wedding.ics"


